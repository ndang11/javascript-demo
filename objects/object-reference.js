//Differences between methods and functions


//In programming, functions and methods are both blocks of code designed to perform specific tasks, but they have distinct characteristics and uses.

//A function is a reusable piece of code that can be called to perform a specific task. It can take input parameters (arguments) and return a value
//A method is similar to a function but is associated with an object. Methods are defined within a class and can operate on data contained within that class. 

// Some differences

//Association: Function: Independent and not associated with any object. Method: Associated with an object and can access the object's data.

//Calling: Function: Called by its name independently. Method: Called using the object's name.

//Data Access: Function: Operates on data passed explicitly. Method: Operates on data within the class implicitly.

//cope: Function: Can be declared and defined anywhere in the code. Method: Declared and defined within a class.



//Differences between camel case and snake case

//Camel case is a naming convention where the first word is in lowercase, and each subsequent word starts with an uppercase letter.
//example
//numberOfCars = 30
//favePhrase = "Hello World"

//Snake case is a naming convention where each word is separated by an underscore (_), and all letters are in lowercase.
//example
//number_of_cars = 30
//fave_phrase = "Hello World"